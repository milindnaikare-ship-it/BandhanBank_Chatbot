// Returns a translator bound to a language, falling back to English per key.
export const makeTr = (lang) => (key, ...args) => {
  const table = D[lang] || D.en;
  const val = table[key] !== undefined ? table[key] : D.en[key];
  return typeof val === "function" ? val(...args) : val;
};

